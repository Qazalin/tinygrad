"""Generates test/mockgpu/qcom/ins.py from Mesa's Freedreno Adreno IR3 ISA XML (a630)."""
from __future__ import annotations
import keyword, pathlib, xml.etree.ElementTree as ET
from tinygrad.helpers import fetch

MESA_TAG, GPU_ID = "mesa-25.2.7", 630
MESA_ISA_URL = f"https://gitlab.freedesktop.org/mesa/mesa/-/raw/{MESA_TAG}/src/freedreno/isa"
XML_FILES = ("ir3.xml", "ir3-common.xml", *(f"ir3-cat{i}.xml" for i in range(8)))
_FLUT = {"e": "math.e", "pi": "math.pi", "1/pi": "1.0 / math.pi", "1/log2(e)": "1.0 / math.log2(math.e)",
         "log2(e)": "math.log2(math.e)", "1/log2(10)": "1.0 / math.log2(10.0)", "log2(10)": "math.log2(10.0)"}

def _bits(el:ET.Element) -> tuple[int, int]:
  lo = int(el.attrib["pos"]) if "pos" in el.attrib else int(el.attrib["low"])
  return lo, int(el.attrib.get("high", lo))

def _py_ident(name:str) -> str:
  out = name.lower().replace(".", "_").replace("-", "_")
  return f"_{out}" if out[0].isdigit() or keyword.iskeyword(out) else out

def generate(out_path:pathlib.Path | None = None) -> str:
  enums:dict[str, list[tuple[int, str]]] = {}
  bitsets:dict[str, ET.Element] = {}
  for fn in XML_FILES:
    root = ET.parse(fetch(f"{MESA_ISA_URL}/{fn}")).getroot()
    for e in root.findall("enum"): enums[e.attrib["name"]] = [(int(v.attrib["val"], 0), v.attrib.get("display", "")) for v in e.findall("value")]
    for b in root.findall("bitset"):
      gens = [(int(g.attrib.get("min", 0)), int(g.attrib.get("max", 9999))) for g in b.findall("gen")]
      if not gens or any(lo <= GPU_ID <= hi for lo, hi in gens): bitsets[b.attrib["name"]] = b

  def chain(name:str) -> list[ET.Element]:
    out, cur = [], name
    while cur and cur in bitsets:
      out.append(bitsets[cur])
      cur = bitsets[cur].attrib.get("extends", "")
    return out[::-1]

  enum_types = {"#type": "IR3Type", "#cat5-type": "IR3Type", "#cond": "IR3Cond"}
  layouts:dict[tuple, int] = {}
  by_cat:list[list[tuple[int, int, int, str]]] = [[] for _ in range(8)]
  for name in sorted(bitsets):
    if name.startswith("#") or not any(b.attrib["name"] == "#instruction" for b in chain(name)): continue
    mask, val, flds = 0, 0, {}
    for b in chain(name):
      for p in b.findall("pattern"):
        lo, hi = _bits(p)
        s = (p.text or "").strip()
        assert len(s) == hi - lo + 1, f"pattern length mismatch {s!r} for {lo}..{hi}"
        for i, ch in enumerate(reversed(s)):
          if ch in ("0", "1"):
            bit = 1 << (lo + i)
            mask, val = mask | bit, (val | bit) if ch == "1" else (val & ~bit)
      for f in b.findall("field"): flds[f.attrib["name"]] = (*_bits(f), f.attrib.get("type", "uint"))
    for lo, hi, _ in flds.values():
      fmask = ((1 << (hi - lo + 1)) - 1) << lo
      mask, val = mask & ~fmask, val & ~fmask
    sig = tuple((_py_ident(k), lo, hi, ft in ("int", "offset", "branch"), enum_types.get(ft)) for k, (lo, hi, ft) in sorted(flds.items()))
    by_cat[(val >> 61) & 7].append((mask, val, layouts.setdefault(sig, len(layouts)), name))

  flut = ", ".join(_FLUT.get(s := d.removeprefix("(").removesuffix(")"), s) for _, d in sorted(enums["#flut"]))
  lines = [
    f"# autogenerated from Mesa ir3.xml ({MESA_TAG}, gen={GPU_ID}) - do not edit",
    "# ruff: noqa: E501,F401,E702",
    "from __future__ import annotations",
    "import math",
    "from tinygrad.dtype import DType, dtypes",
    "from tinygrad.uop import FastEnum",
    "class IR3Type(FastEnum):",
    f"  {'; '.join(f'{d.upper()} = {v}' for v, d in enums['#type'])}",
    "  @property",
    "  def dtype(self) -> DType:",
    "    return (dtypes.half, dtypes.float32, dtypes.uint16, dtypes.uint32, dtypes.int16, dtypes.int32, dtypes.uint8, dtypes.uint8)[self.value]",
    "  @property",
    "  def is_half(self) -> bool: return (self.value & 1) == 0",
    "  @property",
    "  def is_float(self) -> bool: return dtypes.is_float(self.dtype)",
    "class IR3Cond(FastEnum):",
    f"  {'; '.join(f'{d.upper()} = {v}' for v, d in enums['#cond'])}",
    f"FLOAT_IMMS = ({flut})",
    "LAYOUTS:tuple[dict[str, tuple[int, int, bool, type[FastEnum]|None]], ...] = (",
    *(f"  {{{', '.join(f'{k!r}: ({lo}, {hi}, {s}, {e})' for k, lo, hi, s, e in sig)}}}," for sig in layouts),
    ")",
    "DECODE_TABLE:tuple[tuple[tuple[int, int, int, str], ...], ...] = (",
  ]
  for cat in range(8):
    by_cat[cat].sort(key=lambda x: (-x[0].bit_count(), x[2], x[3]))
    items = [f"({m:#018x}, {v:#018x}, {lay}, {op!r})" for m, v, lay, op in by_cat[cat]]
    lines += ["  (", *(f"    {', '.join(items[i:i+4])}," for i in range(0, len(items), 4)), "  ),"]
  content = "\n".join(lines + [")", ""])
  if out_path is not None: out_path.write_text(content)
  return content

if __name__ == "__main__":
  out = pathlib.Path(__file__).with_name("ins.py")
  generate(out)
  print(f"Generated {out} ({len(out.read_text().splitlines())} lines)")
